/**
 * Evento de rastreabilidade — the automatic log of anything worth explaining
 * later (files_design/03 "Evento (histórico/rastreabilidade)").
 *
 * The person never writes or edits one: the system generates it on registration,
 * rate adjustment, and payment with or without a discrepancy. Each Passivo shows
 * its own full log; the Home shows only the last five of the whole product.
 *
 * Named `TraceEvent` because a bare `Event` collides with the DOM's `Event`
 * (src/domain/GLOSSARY.md).
 */

import type {
  BankAccountId,
  Cents,
  EntryId,
  InvestmentId,
  IsoDate,
  LiabilityId,
  RecurrenceId,
  TraceEventId,
} from '@/domain/core'

export const TRACE_EVENT_KINDS = [
  'Registration',
  'RateAdjustment',
  'InstallmentPaid',
  'RecurrencePaid',
  'Discrepancy',
  'Transfer',
] as const
export type TraceEventKind = (typeof TRACE_EVENT_KINDS)[number]

/**
 * files_design/03 §"Evento (histórico/rastreabilidade)" lists the first four
 * types verbatim ("enum: Cadastro, Reajuste de juros, Parcela paga, Recorrência
 * paga"). The fifth, `Discrepancy`, comes from the generalisation in the Figma
 * note `163:4` ("Qualquer divergência (previsto ≠ pago) ... gera um Evento") and
 * in files_design/03 §"Marcar Pago" ("gera um Evento de divergência").
 *
 * `Discrepancy` used to be labelled "Divergência" under the claim that it was a
 * placeholder awaiting Produto's wording. Measured and false: Produto writes the
 * taxonomy in full in the Wireframe, text node `309:25` of the empty state
 * `309:23` "Vazio — Eventos Recentes" — "Reajustes de juros, **divergências de
 * pagamento** e parcelas confirmadas aparecem aqui conforme forem acontecendo."
 * The short form "divergências" is the Home caption, `150:5` / Mockup `549:279`.
 *
 * What IS true is that no frame prints the type on an event row: the Home card
 * (`150:6`..`150:20`, Mockup `549:280`..`549:294`) and the Passivo detail log
 * (`91:134`..`91:145`) are date + description, both columns only. So this map
 * names the enum — the "Tipo" field files_design/03 documents on the Evento
 * object — never a column of a screen.
 */
export const LABEL_TRACE_EVENT_KIND: Record<TraceEventKind, string> = {
  Registration: 'Cadastro',
  RateAdjustment: 'Reajuste de juros',
  InstallmentPaid: 'Parcela paga',
  RecurrencePaid: 'Recorrência paga',
  Discrepancy: 'Divergência de pagamento',
  // ADR-0017 §3. O sexto tipo, acrescentado em 2026-09-11 junto com a linha
  // "Tipo" do files_design/03 — mover valor entre duas posições muda dois
  // números e não deixava rastro nenhum: a pessoa via os dois saldos diferentes
  // do que eram, sem como distinguir isso de uma correção de cadastro.
  //
  // "Transferência" e não "Redirecionamento" porque é o nome do conceito no
  // glossário; "Redirecionar valor" é o rótulo do botão, e este campo nomeia o
  // Tipo no modelo de dados, que nenhum frame imprime numa linha de evento.
  Transfer: 'Transferência',
}

/**
 * "Origem: Passivo específico, ou Lançamento recorrente específico"
 * (files_design/03). `Entry` was added for `@/domain/pending-items` (H13
 * wiring): a divergence on a STANDALONE Lançamento — one with no recurrence and
 * no liability behind it — has neither a Passivo nor a Recorrência to point at,
 * only the Lançamento itself (`POST /api/v1/entries/{id}/payment`).
 */
export type TraceEventOrigin =
  | { readonly kind: 'Liability'; readonly liabilityId: LiabilityId }
  | { readonly kind: 'Recurrence'; readonly recurrenceId: RecurrenceId }
  | { readonly kind: 'Entry'; readonly entryId: EntryId }
  // ADR-0017 §3: uma Transferência nasce de uma posição, não de um Passivo nem
  // de uma Recorrência. A origem gravada é o DESTINO — a única posição que a
  // operação inteira faz existir valor novo —, e a escolha não tem consequência
  // observável hoje, porque nenhuma tela lista o histórico de uma conta ou de
  // um investimento. Fica registrada para quando listar.
  | { readonly kind: 'BankAccount'; readonly bankAccountId: BankAccountId }
  | { readonly kind: 'Investment'; readonly investmentId: InvestmentId }

export interface TraceEvent {
  readonly id: TraceEventId
  readonly date: IsoDate
  readonly kind: TraceEventKind
  readonly origin: TraceEventOrigin
  /**
   * pt-BR, generated by the system, e.g. "Parcela #12 paga: previsto
   * R$ 1.520,00, pago R$ 1.540,00". Stored as text so an old event still reads
   * the way it read the day it happened, even after the debt changed.
   */
  readonly description: string
}

/* -------------------------------------------------------------------------
 * The payload each kind of event needs to describe itself.
 *
 * `id` and `date` live here rather than being read from a clock because the
 * domain never calls `Date.now()` — every function receives what it needs
 * (src/domain/README.md).
 * ---------------------------------------------------------------------- */

interface TraceEventDataBase {
  readonly id: TraceEventId
  readonly date: IsoDate
}

/**
 * "Dívida cadastrada: R$ 320.000,00, 360 parcelas, taxa inicial 0,80% a.m."
 * (Figma `91:145`). The fields are those of a Passivo because that is the only
 * Cadastro any source spells out.
 *
 * P35: não carrega o nome da dívida. A Home o acrescenta na hora de exibir, com
 * o nome ATUAL do Passivo — ver `describeEventForHome` em ./rules.ts.
 *
 * `TraceEventOrigin` também admite Recorrência, mas essa combinação não é
 * construível e não é pergunta de produto: o ÚNICO produtor de evento
 * `Registration` é `liabilityRegisteredEvent` (src/domain/assets/installments.ts),
 * que fixa `origin: { kind: 'Liability' }` — e os três campos abaixo
 * (`originalAmount`, `installmentCount`, `initialRate`) são de passivo, não
 * existem numa recorrência. O que a P19 respondeu é outra coisa, e é sim:
 * evento COM origem em recorrência existe e está desenhado ("Recorrência
 * paga", Figma `150:8`). A união é mais larga do que precisa ser; estreitá-la
 * é refatoração, não decisão pendente.
 */
export interface RegistrationEventData extends TraceEventDataBase {
  readonly originalAmount: Cents
  readonly installmentCount: number
  /** Decimal fraction, same unit as `Liability.monthlyInterestRate`: 0.008 is 0,80% a.m. */
  readonly initialRate: number
}

/** "Taxa de juros reajustada de 0,80% para 0,85% a.m." (files_design/03). */
export interface RateAdjustmentEventData extends TraceEventDataBase {
  readonly previousRate: number
  readonly newRate: number
}

/**
 * "Parcela #12 paga: previsto R$ 1.520,00, pago R$ 1.540,00" (files_design/03)
 * when the amounts differ, "Parcela #11 paga: valor conforme previsto"
 * (Figma 150:17) when they match.
 */
export interface InstallmentPaidEventData extends TraceEventDataBase {
  readonly installmentNumber: number
  readonly plannedAmount: Cents
  readonly paidAmount: Cents
}

/**
 * A recurrence occurrence paid for exactly what was planned. A divergent one is
 * a `Discrepancy`, the case Figma prints verbatim in `150:8` / Mockup `549:282`.
 *
 * P17 claimed no source printed a "Recorrência paga" sentence at all. Measured
 * and half false: the DIVERGENT variant is drawn, in eleven Wireframe frames
 * and in the Mockup. Only the exact-match variant is missing from every frame,
 * and its wording joins the "<assunto> pago" head of `150:8` to the "valor
 * conforme previsto" tail of `150:17`.
 */
export interface RecurrencePaidEventData extends TraceEventDataBase {
  /** The name of the recurrence, as the person typed it ("Aluguel"). */
  readonly subject: string
}

/**
 * "Aluguel pago com divergência: previsto R$ 1.500,00, pago R$ 1.300,00
 * (R$ 200,00 pendente)" — Figma `150:8` (Wireframe) e `549:282` (Mockup).
 * files_design/03 cita a mesma frase truncada, como "ex.:"; ver
 * `describeDiscrepancy` em ./rules.ts para o porquê do sufixo.
 */
export interface DiscrepancyEventData extends TraceEventDataBase {
  readonly subject: string
  readonly plannedAmount: Cents
  readonly paidAmount: Cents
}

/** Which payload goes with which kind — the map `recordEvent` is generic over. */
/**
 * "R$ 5.000,00 redirecionados de Nubank para Tesouro Direto" — ADR-0017 §3.
 *
 * Os nomes viajam no payload, congelados, pelo mesmo motivo que a descrição de
 * um evento é texto gravado e não montado na leitura: renomear a conta depois
 * não pode reescrever o que aconteceu.
 */
export interface TransferEventData extends TraceEventDataBase {
  readonly amount: Cents
  /** Um por instrumento debitado — um bloco agregado debita mais de um. */
  readonly sourceNames: readonly string[]
  readonly destinationName: string
}

export interface TraceEventDataByKind {
  readonly Registration: RegistrationEventData
  readonly RateAdjustment: RateAdjustmentEventData
  readonly InstallmentPaid: InstallmentPaidEventData
  readonly RecurrencePaid: RecurrencePaidEventData
  readonly Discrepancy: DiscrepancyEventData
  readonly Transfer: TransferEventData
}

export type TraceEventData<K extends TraceEventKind = TraceEventKind> = TraceEventDataByKind[K]

/**
 * A TraceEvent before it has an id and a timestamp.
 *
 * Pure domain rules (an amortisation recalculation, a payment discrepancy)
 * produce these: they know WHAT happened but must not read a clock or invent an
 * id, so the store stamps both at the edge (src/domain/README.md, "Pureza").
 */
export type NewTraceEvent = Omit<TraceEvent, 'id'>
