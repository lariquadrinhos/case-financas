/**
 * Eventos de rastreabilidade — `/api/v1/trace-events`.
 *
 * Read-only over HTTP: the person never writes or edits one, the system
 * generates it (files_design/03). The Home reads the last five of the whole
 * product; the Detalhe do Passivo reads the full log of one liability.
 *
 * `description` carries a monetary amount ("Parcela #12 paga: previsto
 * R$ 1.520,00"). It is product data shown on screen and must NEVER be passed to
 * the logger — ADR-0009 §3 says so explicitly.
 */

import { TRACE_EVENT_KINDS } from '@/domain/trace-events'
import { registry, z } from '@/api/registry'
import { API_BASE_PATH } from '@/api/http'
import { errorResponses, idSchema, isoDateSchema, listEnvelope } from './common'

export const traceEventOriginSchema = registry.register(
  'TraceEventOrigin',
  z.discriminatedUnion('kind', [
    z.object({ kind: z.literal('Liability'), liabilityId: idSchema }),
    z.object({ kind: z.literal('Recurrence'), recurrenceId: idSchema }),
    z.object({ kind: z.literal('Entry'), entryId: idSchema }),
  ]),
)

export const traceEventSchema = registry.register(
  'TraceEvent',
  z.object({
    id: idSchema,
    date: isoDateSchema,
    kind: z.enum(TRACE_EVENT_KINDS),
    origin: traceEventOriginSchema,
    /** pt-BR, generated by the system and stored as text so an old event still reads as it did. */
    description: z.string(),
    /**
     * O nome ATUAL do Passivo de origem, `null` quando a origem não é um
     * Passivo. Não faz parte do evento: é o dado que falta à Home para montar a
     * redação dela (`describeEventForHome`), já que a gravada é a do Detalhe do
     * Passivo, que não repete o nome — P35, decidido em 2026-09-09.
     */
    subject: z.string().nullable(),
  }),
)

registry.registerPath({
  method: 'get',
  path: `${API_BASE_PATH}/trace-events`,
  tags: ['Trace events'],
  summary: 'Lista eventos de rastreabilidade, do mais recente para o mais antigo',
  request: {
    query: z.strictObject({
      liabilityId: idSchema.optional(),
      recurrenceId: idSchema.optional(),
      /** The Home card "Eventos Recentes" asks for 5 (files_design/03). */
      limit: z.coerce.number().int().min(1).max(200).default(50),
    }),
  },
  responses: {
    200: {
      description: 'Eventos.',
      content: { 'application/json': { schema: listEnvelope(traceEventSchema) } },
    },
    ...errorResponses(422),
  },
})
